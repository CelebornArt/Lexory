  function detectDeviceLanguage() {
    const candidates = Array.isArray(navigator.languages) && navigator.languages.length > 0
      ? navigator.languages
      : [navigator.language || 'en'];

    for (const raw of candidates) {
      const code = String(raw || '').toLowerCase().split('-')[0];
      if (TRANSLATIONS[code]) return code;
    }
    return 'en';
  }

  function resolveEffectiveLang(settingValue) {
    if (!settingValue || settingValue === 'auto') {
      return detectDeviceLanguage();
    }
    return TRANSLATIONS[settingValue] ? settingValue : 'en';
  }

  function getTranslation(langCode, key, vars) {
    const table = TRANSLATIONS[langCode] || BASE_EN;
    let template = table[key] !== undefined ? table[key] : BASE_EN[key];
    if (template === undefined) return key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        template = template.replaceAll(`{${k}}`, String(v));
      }
    }
    return template;
  }

  window.WordCollectorI18n = {
    UI_LANGUAGES,
    detectDeviceLanguage,
    resolveEffectiveLang,
    getTranslation,
  };
